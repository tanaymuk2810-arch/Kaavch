export type StrKey = keyof typeof STR;

export function sx(key: StrKey, lang: string): string {
  const v = STR[key];
  return v[lang as keyof L10n] ?? v.en;
}

export function fmt(key: StrKey, lang: string, m: Record<string, string | number>): string {
  let s: string = sx(key, lang);
  for (const [k, v] of Object.entries(m)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}